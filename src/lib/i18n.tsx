export type Dictionary = (typeof DICT)[UiLang];

type I18nContextValue = {
  lang: UiLang;
  setLang: (lang: UiLang) => void;
  t: Dictionary;
};

const I18nContext = createContext<I18nContextValue>({
  lang: "es",
  setLang: () => {},
  t: DICT.es,
});

export function I18nProvider({
  children,
  onLangChange,
}: {
  children: ReactNode;
  onLangChange?: (lang: UiLang) => void;
}) {
  const savedLang = useSyncExternalStore(subscribeLanguage, storedLanguage, () => "es" as UiLang);
  const [selectedLang, setLangState] = useState<UiLang | null>(null);
  const lang = selectedLang ?? savedLang;

  useEffect(() => {
    document.documentElement.lang = lang;
    onLangChange?.(lang);
  }, [lang, onLangChange]);

  const setLang = useCallback(
    (next: UiLang) => {
      setLangState(next);
      try {
        localStorage.setItem(STORAGE_KEY, next);
        document.documentElement.lang = next;
      } catch {
        /* ignore storage errors */
      }
      onLangChange?.(next);
    },
    [onLangChange],
  );

  return (
    <I18nContext.Provider value={{ lang, setLang, t: DICT[lang] }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
